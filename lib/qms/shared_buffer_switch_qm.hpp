#ifndef shared_buffer_switch_qm_hpp
#define shared_buffer_switch_qm_hpp

#include "queuing_module.hpp"
#include "shared_buffer_route_policy.hpp"

using namespace std;

struct SharedBufferSwitchInfo {
    enum class TimingMode {
        DEQ_FIRST = 0,
        ENQ_FIRST = 1,
    };

    unsigned int ingress_queue_cnt = 1;
    unsigned int egress_queue_cnt = 1;
    unsigned int buffer_slot_cnt = MAX_QUEUE_SIZE;
    unsigned int ingress_pool_size = 0;
    unsigned int headroom_pool_size = 0;
    unsigned int egress_lossless_pool_size = 0;
    vector<unsigned int> ingress_ser_factor;
    vector<unsigned int> egress_ser_factor;
    TimingMode timing_mode = TimingMode::DEQ_FIRST;
};

class SharedBufferSwitchQM : public QueuingModule {
public:
    SharedBufferSwitchQM(cid_t id,
                         unsigned int total_time,
                         vector<QueueInfo> in_queue_info,
                         vector<QueueInfo> out_queue_info,
                         SharedBufferSwitchInfo info,
                         SharedBufferRoutePolicy* route_policy,
                         NetContext& net_ctx);

    void add_constrs(NetContext& net_ctx, map<string, expr>& constr_map) override;

    unsigned int micro_step_cnt() const;
    unsigned int deq_step_idx() const;
    int ingress_queue_for_step(unsigned int k) const;
    unsigned int ingress_pool_cap() const;
    unsigned int headroom_pool_cap() const;
    unsigned int egress_lossless_pool_cap() const;
    unsigned int ingress_serialization_factor(unsigned int q) const;
    unsigned int egress_serialization_factor(unsigned int e) const;

    const expr& ingress_paused(unsigned int q, unsigned int t) const;
    const expr& pfc_blocked(unsigned int e, unsigned int t) const;
    const expr& slot_pkt(unsigned int b, unsigned int t, unsigned int k) const;
    string debug_model_str(model& m, NetContext& net_ctx, unsigned int t) const;

private:
    // TODO(shared-buffer-semantics): Keep this class as the shared-buffer core and inject a
    // SharedBufferSemanticPolicy from SONiCSwitch instead of splitting the core into multiple
    // subclasses. The common skeleton here should continue to own buffer-slot state, admission,
    // pool accounting, and XOFF/XON threshold logic; the policy should provide the profile-
    // specific meaning of ingress-visible arrivals, sender-visible pause timing, and any
    // residual/in-flight traffic semantics needed by PRECISE_PFC.
    void add_proc_vars(NetContext& net_ctx) override;
    void add_scaffold_constrs(NetContext& net_ctx, map<string, expr>& constr_map);
    SBQueue* ingress_sb_queue(unsigned int q);
    SBQueue* egress_sb_queue(unsigned int e);
    const SBQueue* ingress_sb_queue(unsigned int q) const;
    const SBQueue* egress_sb_queue(unsigned int e) const;

    SharedBufferSwitchInfo sb_info_;
    SharedBufferRoutePolicy* route_policy_;

    // Shared-buffer internal state lives at micro-step granularity [..][t][k].
    vector<vector<vector<expr>>> buf_pkt_;   // [b][t][k] pkt
    vector<vector<vector<expr>>> buf_in_;    // [b][t][k] int, ingress owner or -1
    vector<vector<vector<expr>>> buf_e_;     // [b][t][k] int, egress owner or -1
    vector<vector<vector<expr>>> buf_stamp_; // [b][t][k] int, -1 means empty

    vector<vector<expr>> ingress_paused_; // [q][t] bool, local pause state generated by switch

    // TODO(shared-buffer-switch): This per-queue, per-microstep occupancy representation is
    // O(T * Q^2) because k scales with the ingress-queue count. If solver cost becomes dominant,
    // compress these ledgers into slot-boundary per-queue states plus per-microstep aggregate
    // totals / active-ingress deltas.
    vector<vector<vector<expr>>> ingress_pool_occ_;         // [q][t][k] int
    vector<vector<expr>> ingress_pool_total_occ_;           // [t][k] int
    vector<vector<vector<expr>>> headroom_pool_occ_;        // [q][t][k] int
    vector<vector<expr>> headroom_pool_total_occ_;          // [t][k] int
    vector<vector<vector<expr>>> egress_lossless_pool_occ_; // [e][t][k] int
    vector<vector<expr>> egress_lossless_pool_total_occ_;   // [t][k] int

    vector<vector<vector<expr>>> admit_in_;          // [q][t][k] bool
    vector<vector<vector<expr>>> admit_e_;           // [e][t][k] bool
    vector<vector<vector<expr>>> admit_;             // [q][t][k] bool
    vector<vector<vector<expr>>> alloc_in_;          // [q][t][k] bool
    vector<vector<vector<expr>>> alloc_hdr_;         // [q][t][k] bool
    vector<vector<vector<expr>>> alloc_eg_lossless_; // [e][t][k] bool

    vector<vector<vector<vector<expr>>>> write_slot_; // [q][b][t][k] bool
    vector<vector<vector<expr>>> read_slot_;          // [b][t][k] bool

    vector<vector<expr>> min_stamp_e_; // [e][t] int
    vector<vector<expr>> has_pkt_e_;   // [e][t] bool
    vector<vector<expr>> pfc_blocked_; // [e][t] bool, egress has pending pkt but is paused
};

#endif /* shared_buffer_switch_qm_hpp */
